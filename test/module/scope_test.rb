require_relative "scope_helper"

class ScopeTest < Minitest::Test
  LOCAL = Dagger::Clients::Core::ModuleSourceKind::LOCAL_SOURCE
  GIT = Dagger::Clients::Core::ModuleSourceKind::GIT_SOURCE
  LIB = FakeClient.new("lib", LOCAL, "", "", ".dagger/modules/lib", "")
  SHA = "419c4afea78603265c40e273c455623a0291922e".freeze
  OTHER = ("0" * 40).freeze
  CLONE = "http://h/r.git".freeze
  TARGET = "v1.0.0-beta.21".freeze

  def generate(files, cwd: "/app", is_module: true, clients: [], name: "app", **)
    ws = FakeWorkspace.new(FakeTree.new(files), cwd)
    OfflineScope.new(ws:, is_module:, name:, clients:, sdk: nil, image: "ruby", target_version: TARGET, **).generated
  end

  def test_members_are_written_whole_and_the_cwd_kept
    result = generate({ "app/Gemfile" => "x", "app/sdk/.dagger-generated" => "sdk", "app/sdk/old.rb" => "stale" },
                      clients: [LIB])

    assert_equal "/app", result.cwd
    refute result.tree.files.key?("app/sdk/old.rb")
    assert_equal "core", result.tree.files["app/clients/core/.dagger-generated"]
    assert_equal "/.dagger/modules/lib", result.tree.files["app/clients/lib/ref"]
    assert_equal <<~RUBY, result.tree.files["app/dagger.gemfile"]
      # Code generated by dagger. DO NOT EDIT.
      gem "dagger-sdk", path: "sdk"
      gem "dagger-clients-core", path: "clients/core"
      gem "dagger-clients-roots", path: "clients/roots"
      gem "dagger-clients-lib", path: "clients/lib"
    RUBY
  end

  def test_a_directory_where_a_member_goes_that_the_sdk_did_not_write_is_refused
    [{ "app/sdk/mine.rb" => "" }, { "app/sdk/.dagger-generated" => "client" },
     { "app/clients/core/.dagger-generated" => "core\n\n" }, { "app/clients/lib/x.rb" => "" }].each do |files|
      error = assert_raises(RubySdk::Error, files.inspect) { generate(files.merge("app/Gemfile" => ""), clients: [LIB]) }
      assert_match(/was not written by dagger generate/, error.message)
    end
  end

  def test_a_marked_client_no_longer_declared_is_deleted_and_nothing_else
    files = { "app/Gemfile" => "", "app/clients/gone/.dagger-generated" => "client", "app/clients/gone/a.rb" => "",
              "app/clients/mine/a.rb" => "", "app/clients/odd/.dagger-generated" => "client-ish",
              "app/clients/edited/.dagger-generated" => "client\n" }
    result = generate(files)

    refute(result.tree.files.keys.any? { it.start_with?("app/clients/gone/", "app/clients/edited/") })
    assert result.tree.files.key?("app/clients/mine/a.rb")
    assert result.tree.files.key?("app/clients/odd/.dagger-generated")
  end

  def test_clients_that_become_one_member_are_refused
    clients = [LIB, LIB.with(module_name: "LIB", source_root_subpath: "other")]

    assert_raises(RubySdk::Error) { generate({ "app/Gemfile" => "" }, clients:) }
  end

  def test_a_git_client_is_pinned_and_a_local_one_is_rooted
    git = FakeClient.new("dep", GIT, "github.com/acme/dep@v1", "abc123", "dep", "https://github.com/acme/dep")
    scope = OfflineScope.new(ws: FakeWorkspace.new(FakeTree.new({}), "/"), is_module: false, name: "",
                             clients: [git, LIB.with(source_root_subpath: "./lib/")], sdk: nil, image: "ruby",
                             target_version: TARGET)

    assert_equal([%w[dep github.com/acme/dep@v1 abc123], ["lib", "/lib", nil]],
                 scope.client_members.map { [it.dir, it.ref, it.pin] })
    assert_equal "/", RubySdk::Scope.local_ref(".")
  end

  def test_a_git_client_of_the_git_workspace_is_rooted_and_another_commit_pinned
    ws = FakeWorkspace.new(FakeTree.new({}), "/", address: "#{CLONE}@main", commit: SHA)
    clients = [FakeClient.new("dep", GIT, "#{CLONE}#main:dep", SHA, "dep", CLONE),
               FakeClient.new("lib", GIT, "#{CLONE}#v1:lib", OTHER, "lib", CLONE)]
    scope = OfflineScope.new(ws:, is_module: false, name: "", clients:, sdk: nil, image: "ruby", target_version: TARGET)

    assert_equal([["dep", "/dep", nil], ["lib", "#{CLONE}#v1:lib", OTHER]],
                 scope.client_members.map { [it.dir, it.ref, it.pin] })
  end

  def test_a_git_fake_workspace_keeps_its_address_and_commit_through_each_copy
    ws = FakeWorkspace.new(FakeTree.new("a/x" => ""), "/", address: "#{CLONE}@main", commit: SHA)

    [ws.with_workdir(path: "a"), ws.without_directory(path: "a"), ws.write("b", "")].each do |copy|
      assert_equal ["#{CLONE}@main", SHA], [copy.address, copy.git.head.commit]
    end
  end

  def test_a_git_client_without_a_pin_is_refused
    git = FakeClient.new("dep", GIT, "github.com/acme/dep@v1", "", "dep", "https://github.com/acme/dep")
    scope = OfflineScope.new(ws: FakeWorkspace.new(FakeTree.new({}), "/"), is_module: false, name: "",
                             clients: [git], sdk: nil, image: "ruby", target_version: TARGET)

    error = assert_raises(RubySdk::Error) { scope.client_members }
    assert_match(%r{github.com/acme/dep@v1 has no pinned commit}, error.message)
  end

  def test_a_scope_at_the_root_writes_at_the_root
    result = generate({ "Gemfile" => "" }, cwd: "/", is_module: false)

    assert_equal "/", result.cwd
    assert_equal "sdk", result.tree.files["sdk/.dagger-generated"]
  end

  def test_manifests_a_ruby_module_cannot_carry_are_refused_before_anything_is_written
    {
      %([runtime]\nsource = "python"\n) => /\[runtime\]/,
      %([[dependencies]]\nname = "x"\nsource = "x"\n) => /\[\[dependencies\]\]/,
      %(name = "app"\ninclude = ["a"]\n) => /include/,
      %(name = "app"\nsource = "src"\n) => /source/,
      %(name = "app"\nsource = "."\ninclude = ["a"]\n) => /\A[^;]*include[^;]*\z/,
      %(name = "app"\nengineVersion = "v1"\n) => /engineVersion/,
      %(name = "app"\n[entrypoint]\nkind = "dang"\nsource = "./elsewhere"\n) => /\[entrypoint\] source/,
      %(name = "app"\n[entrypoint]\nkind = "module"\nsource = "./sdk/entrypoint"\n) => /\[entrypoint\] kind/,
      %(name = [) => /not valid TOML/
    }.each do |toml, message|
      error = assert_raises(RubySdk::Error) { generate({ "app/Gemfile" => "", "app/dagger-module.toml" => toml }) }
      assert_match message, error.message
    end
  end

  def test_a_dagger_json_is_refused_not_migrated
    error = assert_raises(RubySdk::Error) { generate({ "app/Gemfile" => "", "app/dagger.json" => "{}" }) }

    assert_match(/dagger\.json/, error.message)
  end

  def test_the_generated_manifest_has_a_name_and_the_entrypoint_only
    result = generate({ "app/Gemfile" => "", "app/dagger-module.toml" => RubySdk::Manifest.render("old") })

    assert_equal %(name = "app"\n\n[entrypoint]\nkind = "dang"\nsource = "./sdk/entrypoint"\n),
                 result.tree.files["app/dagger-module.toml"]
    assert_empty RubySdk::Manifest.objections(result.tree.files["app/dagger-module.toml"])
  end

  def test_a_module_rooted_at_its_own_directory_is_regenerated
    result = generate({ "app/Gemfile" => "", "app/dagger-module.toml" => %(name = "app"\nsource = "."\n) })

    assert_equal RubySdk::Manifest.render("app"), result.tree.files["app/dagger-module.toml"]
  end

  def test_a_plain_scope_has_no_manifest
    result = generate({ "app/Gemfile" => "" }, is_module: false)

    refute result.tree.files.key?("app/dagger-module.toml")
  end

  def test_a_ruby_version_setting_is_written
    result = generate({ "app/Gemfile" => "" }, ruby_version: "3.4")

    assert_equal "3.4\n", result.tree.files["app/.ruby-version"]
  end

  def test_the_client_root_is_the_directory_of_the_nearest_gemfile
    tree = FakeTree.new("app/Gemfile" => "", "Gemfile" => "", "app/clients/lib/dagger-clients-lib.gemspec" => "")

    assert_equal "app", RubySdk::Scope.find_root(FakeWorkspace.new(tree, "/app/clients/lib"))
    assert_equal ".", RubySdk::Scope.find_root(FakeWorkspace.new(tree, "/other"))
    assert_nil RubySdk::Scope.find_root(FakeWorkspace.new(FakeTree.new({}), "/x"))
  end

  def test_a_scope_without_a_gemfile_gets_one_that_evaluates_the_sdk_gemfile
    result = generate({}, is_module: false)

    assert_includes result.tree.files["app/Gemfile"], 'eval_gemfile "dagger.gemfile"'
  end

  def test_a_new_module_keeps_the_gemfile_of_its_template
    sdk = FakeTree.new("templates/default/Gemfile" => "gem \"steep\"\n",
                       "templates/default/lib/{{file}}.rb.tmpl" => "class {{class}}; end\n")
    ws = FakeWorkspace.new(FakeTree.new({}), "/app")
    files = OfflineScope.new(ws:, is_module: true, name: "app", clients: [], sdk:, image: "ruby",
                             target_version: TARGET, template: "default").generated.tree.files

    assert_equal ["gem \"steep\"\n", "class App; end\n"], files.values_at("app/Gemfile", "app/lib/app.rb")
  end

  def test_what_the_module_dang_toml_cannot_carry_is_refused_before_anything_is_written
    files = { "app/Gemfile" => "", "app/sdk/.dagger-generated" => "sdk",
              "app/sdk/entrypoint/dang.toml" => %(dang = "2.0"\n) }
    error = assert_raises(RubySdk::Error) { generate(files) }

    assert_match(%r{app/sdk/entrypoint/dang\.toml has what}, error.message)
    assert_includes error.message, %(dang = "2.0")
  end

  def test_an_ancestor_a_new_dang_toml_would_hide_is_refused_and_one_it_would_not_stays
    pinned = { "app/Gemfile" => "", "app/dang.toml" => %([imports.Dagger]\ndagger = "v1.0.0-beta.19"\n) }
    error = assert_raises(RubySdk::Error) { generate(pinned) }

    assert_includes error.message,
                    "app/dang.toml has what generating sdk/entrypoint/dang.toml would hide: imports.Dagger"

    plain = pinned.merge("app/dang.toml" => %(dang = "2.1"\n\n[imports.Dagger]\ndagger = true\n))

    assert_equal plain["app/dang.toml"], generate(plain).tree.files["app/dang.toml"]
  end

  def test_with_the_module_dang_toml_in_place_no_ancestor_counts
    files = { "app/Gemfile" => "", "app/sdk/.dagger-generated" => "sdk", "app/sdk/entrypoint/dang.toml" => "",
              "app/dang.toml" => %([imports.Dagger]\ndagger = "v1.0.0-beta.19"\n), "dang.toml" => "pinned = true\n" }

    assert_equal files["app/dang.toml"], generate(files).tree.files["app/dang.toml"]
  end

  def test_above_the_module_nothing_counts
    files = { "app/Gemfile" => "", "dang.toml" => %([imports.Dagger]\ndagger = "v1.0.0-beta.19"\n) }

    assert_equal files["dang.toml"], generate(files).tree.files["dang.toml"]
  end

  def test_a_plain_scope_has_no_dang_toml_to_answer_for
    files = { "app/Gemfile" => "", "app/dang.toml" => %([imports.Dagger]\ndagger = "v1.0.0-beta.19"\n) }

    assert_equal files["app/dang.toml"], generate(files, is_module: false).tree.files["app/dang.toml"]
  end
end
