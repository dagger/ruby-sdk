module Dagger
  module Mod
    # A module's container, described once: generation builds it through the
    # API to lock and to describe the module, and renders the same steps to
    # the build.dang its entrypoint runs.
    #
    # A module that uses path gems outside its directory builds from its
    # context directory, where it sits at a subpath beside them: /src is the
    # context, and the module's directory the working directory.
    class Build
      EXCLUDES = %w[.bundle vendor/bundle].freeze
      CONTEXT_EXCLUDES = %w[**/.bundle **/vendor/bundle].freeze
      DEPENDENCY_FILES = %w[Gemfile Gemfile.lock dagger.gemfile].freeze
      CACHE_VOLUME = "ruby-sdk-bundle".freeze
      CACHE_PATH = "/cache/bundle".freeze
      HEADER = "# Code generated by dagger. DO NOT EDIT.\n".freeze

      attr_reader :image, :module_name, :gemspecs, :outside, :outside_files, :module_path

      # gemspecs: the path gems' gemspecs, relative to the module, which is
      # all of them that Bundler reads to install. outside: the directories
      # of the path gems outside the module, relative to it, which install
      # with all their files, since a gemspec reads what it likes;
      # outside_files: the files outside it Bundler reads, such as an
      # evaluated Gemfile; module_path: the module's directory in the
      # workspace.
      def initialize(image:, module_name:, gemspecs:, outside: [], outside_files: [], module_path: ".")
        @image = image
        @module_name = module_name
        @gemspecs = gemspecs
        @outside = outside
        @outside_files = outside_files
        @module_path = module_path
      end

      def context? = !(outside + outside_files).empty?

      def env(frozen: true, development: false, subpath: nil)
        variables = {
          "BUNDLE_GEMFILE" => "#{src(subpath)}/Gemfile", "BUNDLE_PATH" => "/usr/local/bundle",
          "BUNDLE_FROZEN" => frozen ? "true" : "false", "BUNDLE_WITHOUT" => "development",
          "BUNDLE_USER_CACHE" => user_cache(development),
          "DAGGER_MODULE" => module_name, "DAGGER_MAIN_OBJECT" => Naming.to_camel(module_name),
          "DAGGER_MODULE_FILE" => Naming.module_file(module_name)
        }
        development ? variables.except("BUNDLE_WITHOUT") : variables
      end

      # The gems install from the Gemfiles and the path gems' gemspecs alone,
      # before the rest of the source arrives, so an edit to lib/, sdk/ or
      # clients/ does not reinstall them; path gems outside the module come
      # whole, since a gemspec reads what it likes. With development, the
      # Gemfile's development group installs too, for tools such as Steep:
      # never in the module's own container. source is the context directory
      # when the build has one, with the module at subpath.
      def installed(root, source, development: false, subpath: nil)
        dependencies = Type.new(dependencies(root, source, subpath:))
        base(root, env(development:, subpath:), subpath).select("withDirectory", path: "/src", source: dependencies)
                                                        .select("withExec", args: %w[bundle install])
                                                        .select("withDirectory", path: "/src", source:,
                                                                                 exclude: excludes(subpath))
      end

      def lock(root, source, files: DEPENDENCY_FILES, subpath: nil)
        dependencies = Type.new(dependencies(root, source, files:, subpath:))
        base(root, env(frozen: false, subpath:), subpath).select("withDirectory", path: "/src", source: dependencies)
                                                         .select("withExec", args: %w[bundle lock])
                                                         .select("file", path: "#{src(subpath)}/Gemfile.lock")
      end

      # The module's directory below the one that holds it and its path gems
      # outside it: the end of its path that its context and its workspace
      # share, which build.dang trims from the context's subpath.
      def tail = module_path.split("/").last(ups).join("/")

      def to_dang = context? ? format(CONTEXT, **dang_parts) : format(ALONE, **dang_parts)

      ALONE = <<~DANG.freeze
        %<header>s
        type RubyModuleBuild {
          pub source: Directory!
          pub moduleName: String!

          new(source: Directory!, moduleName: String!) {
            self.source = source
            self.moduleName = moduleName
            self
          }

          pub installed: Container! {
            let dependencies = [
        %<files>s    ].reduce(directory) { files, path =>
              if (source.exists(path)) {
                files.withNewFile(path, source.file(path).contents)
              } else {
                files
              }
            }
            container
              .from(%<image>s)
        %<env>s      .withMountedCache(%<cache_path>s, cacheVolume(%<cache_volume>s))
              .withWorkdir("/src")
              .withDirectory("/src", dependencies)
              .withExec(["sh", "-c", %<install>s])
              .withDirectory("/src", source, exclude: %<excludes>s)
          }
        }
      DANG

      CONTEXT = <<~DANG.freeze
        %<header>s
        # source is the module's context directory, where the module sits at
        # subpath, beside the path gems it uses outside its directory.
        type RubyModuleBuild {
          pub source: Directory!
          pub subpath: String!
          pub moduleName: String!

          new(source: Directory!, subpath: String!, moduleName: String!) {
            self.source = source
            self.subpath = subpath
            self.moduleName = moduleName
            self
          }

          pub installed: Container! {
            let anchor = subpath.trimSuffix(%<tail>s)
            let dependencies = [
        %<files>s    ].reduce(directory) { files, path =>
              if (source.exists(subpath + "/" + path)) {
                files.withNewFile(subpath + "/" + path, source.file(subpath + "/" + path).contents)
              } else {
                files
              }
            }
        %<outside>s    container
              .from(%<image>s)
        %<env>s      .withMountedCache(%<cache_path>s, cacheVolume(%<cache_volume>s))
              .withWorkdir("/src/" + subpath)
              .withDirectory("/src", %<layer>s)
              .withExec(["sh", "-c", %<install>s])
              .withDirectory("/src", source, exclude: %<context_excludes>s)
          }
        }
      DANG

      private

      def ups = (outside + outside_files).map { |path| path.split("/").take_while { it == ".." }.size }.max || 0

      # A path gem's directory below the one that holds the module and them.
      def anchored(dir)
        parts = dir.split("/").reduce(tail.split("/")) do |kept, part|
          part == ".." ? kept.first(kept.size - 1) : kept + [part]
        end
        parts.join("/")
      end

      def src(subpath) = subpath ? "/src/#{subpath}" : "/src"

      def excludes(subpath) = subpath ? CONTEXT_EXCLUDES : EXCLUDES

      def dang_parts
        { header: HEADER, files: dang_list(DEPENDENCY_FILES + gemspecs), outside: dang_outside, layer: dang_layer,
          tail: tail.dump, image: image.dump, env: dang_env,
          cache_path: CACHE_PATH.dump, cache_volume: CACHE_VOLUME.dump, install: JSON.generate(call_install),
          excludes: dang_strings(EXCLUDES), context_excludes: dang_strings(CONTEXT_EXCLUDES) }
      end

      # At call time a failed install most likely follows a Gemfile, lock or
      # client edited without generation; the hint comes after Bundler's error.
      def call_install = "bundle install || { status=$?; echo 'ruby-sdk: #{REGENERATE_HINT}' >&2; exit $status; }"

      # Contents, not files: the module's source has no content digest, so a
      # file of it would key the install on any edit to the module. A missing
      # file is left out, for Bundler to name what is missing.
      def dang_list(names) = names.map { "      #{it.dump},\n" }.join

      def dang_strings(values) = JSON.generate(values).gsub(",", ", ")

      # The directory the dependencies end up in, the last that adds to it.
      def dang_layer
        return "outside" unless outside_files.empty?

        outside.empty? ? "dependencies" : "gems"
      end

      # The path gems outside the module, then the files outside it, each
      # file by its contents: the context carries the module's source, so a
      # directory of it would key the install on any edit to the module. The
      # whole context, exact, arrives after the install. Each reduce only when
      # it has something to add.
      def dang_outside
        gem = %(source.directory(anchor + path).filter(exclude: #{dang_strings(EXCLUDES)}))
        gems = "    let gems = [\n#{dang_list(outside.map { anchored(it) })}    ]" \
               ".reduce(dependencies) { files, path =>\n      " \
               "#{gem}.glob(\"**\")\n        .filter { file => file.hasSuffix(\"/\") == false }\n        " \
               ".reduce(files) { copied, file =>\n          " \
               "copied.withNewFile(anchor + path + \"/\" + file, #{gem}.file(file).contents)\n        }\n    }\n"
        files = "    let outside = [\n#{dang_list(outside_files.map { anchored(it) })}    ]" \
                ".reduce(#{outside.empty? ? "dependencies" : "gems"}) { files, path =>\n      " \
                "files.withNewFile(anchor + path, source.file(anchor + path).contents)\n    }\n"
        "#{gems unless outside.empty?}#{files unless outside_files.empty?}"
      end

      # Bundler names its temporary files by process ID, which repeats across
      # containers: two builds writing one directory of the shared volume at
      # once fail to rename them. Each module, and its development install,
      # has a directory of its own.
      def user_cache(development) = "#{CACHE_PATH}/#{module_name}#{"-development" if development}"

      def dang_env
        env.map do |name, value|
          rendered = if name == "DAGGER_MODULE" then "moduleName"
                     elsif name == "BUNDLE_USER_CACHE" then %("#{CACHE_PATH}/" + moduleName)
                     elsif name == "BUNDLE_GEMFILE" && context? then %("/src/" + subpath + "/Gemfile")
                     else value.dump
                     end
          "      .withEnvVariable(#{name.dump}, #{rendered})\n"
        end.join
      end

      def base(root, variables, subpath)
        container = root.select("container").select("from", address: image)
        variables.each { |name, value| container = container.select("withEnvVariable", name:, value:) }
        cache = Type.new(root.select("cacheVolume", key: CACHE_VOLUME))
        container.select("withMountedCache", path: CACHE_PATH, cache:).select("withWorkdir", path: src(subpath))
      end

      def dependencies(root, source, files: DEPENDENCY_FILES, subpath: nil)
        query = (files + gemspecs).reduce(root.select("directory")) do |selected, name|
          path = subpath ? "#{subpath}/#{name}" : name
          selected.select("withFile", path:, source: Type.new(source.query.select("file", path:)))
        end
        return query unless subpath

        anchor = subpath.delete_suffix(tail)
        query = outside.reduce(query) do |selected, dir|
          path = "#{anchor}#{anchored(dir)}"
          selected.select("withDirectory", path:, source: Type.new(source.query.select("directory", path:)),
                                           exclude: EXCLUDES)
        end
        outside_files.reduce(query) do |selected, file|
          path = "#{anchor}#{anchored(file)}"
          selected.select("withFile", path:, source: Type.new(source.query.select("file", path:)))
        end
      end
    end
  end
end
