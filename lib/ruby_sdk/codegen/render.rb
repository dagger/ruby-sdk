class RubySdk
  module Codegen
    # Ruby source and RBS for the types of one package. A type reference is
    # resolved against the schema; every constant outside the package is
    # written from the top level, because core defines File, JSON, Module and
    # Error, which shadow Ruby's own.
    class Render
      HEADER = "# Code generated by dagger. DO NOT EDIT.\n".freeze

      CORE = "::Dagger::Clients::Core".freeze

      # A client package names its own types bare, and core's from the top
      # level; a type of another client is refused. Qualified, its own types
      # are named from the top level too, for code outside the package.
      def initialize(schema, namespace, owner: nil, qualified: false)
        @schema = schema
        @namespace = namespace
        @owner = owner
        @qualified = qualified
      end

      def ref(name)
        type_owner = Partition.owner(@schema[name])
        return own(name) if type_owner == @owner
        raise Error, %(the client "#{@owner}" names "#{name}" of the client "#{type_owner}") if type_owner

        "#{CORE}::#{Naming.constant(name)}"
      end

      def ruby(type)
        body =
          case type.fetch("kind")
          when "OBJECT" then object(type)
          when "INTERFACE" then interface(type)
          when "ENUM" then enum(type)
          when "SCALAR" then "class #{const(type)} < ::Dagger::Scalar\nend\n"
          when "INPUT_OBJECT" then input(type)
          else raise Error, "cannot render #{type["kind"]} #{type["name"]}"
          end
        "#{HEADER}\n#{nest(docs(type) + body)}"
      end

      def rbs(type)
        body =
          case type.fetch("kind")
          when "OBJECT" then object_rbs(type)
          when "INTERFACE" then interface_rbs(type)
          when "ENUM" then enum_rbs(type)
          when "SCALAR" then "class #{const(type)} < ::Dagger::Scalar\nend\n"
          when "INPUT_OBJECT" then input_rbs(type)
          end
        "#{HEADER}\n#{nest(body.to_s)}"
      end

      def nest(body) = Package.nest(@namespace, body)

      def const(type) = Naming.constant(type.fetch("name"))

      # A module's main object is named like its client's namespace, where a
      # bare name would be ambiguous to read.
      def own(name)
        constant = Naming.constant(name)
        @qualified || constant == @namespace.split("::").last ? "::#{@namespace}::#{constant}" : constant
      end

      def generated?(name) = !@schema.builtin_scalar?(name) && name != "Void"

      def entry_function(field)
        args = ordered_args(field)
        params = [*args.map { param(it, session: true) }, "session: nil"]
        name = Naming.method_name(field["name"])
        "#{docs(field, args)}def self.#{name}(#{params.join(", ")})\n  " \
          "#{instance_const(Schema.named(field["type"]))}.new(::Dagger::Client.root(TARGET, #{field["name"].dump}, " \
          "#{args_hash(args, session: true)}, session:))\nend\n"
      end

      def contributed_function(parent, field)
        args = ordered_args(field)
        receiver = Naming.argument_name(Naming.snake(parent["name"]))
        receiver += "_" if args.any? { Naming.argument_name(it["name"]) == receiver }
        selection = "::Dagger::Client.select(#{receiver}, TARGET, #{field["name"].dump}, #{args_hash(args)})"
        params = [receiver, *args.map { param(it) }].join(", ")
        "#{docs(field, args)}def self.#{Naming.method_name(field["name"])}(#{params})\n" \
          "#{indent(body(parent, field, selection))}end\n"
      end

      def entry_function_rbs(field)
        params = [*ordered_args(field).map { param_rbs(it, session: true) }, "?session: ::Dagger::Session?"]
        "def self.#{Naming.method_name(field["name"])}: (#{params.join(", ")}) -> #{output_type(field)}"
      end

      # The entry point as an instance method named name that passes every argument through.
      def root_function(field, name)
        args = ordered_args(field)
        passed = [*args.map { "#{ruby_argument(it, session: true)}:" }, "session:"].join(", ")
        "#{docs(field, args)}def #{name}(#{[*args.map { param(it, session: true) }, "session: nil"].join(", ")})\n  " \
          "::#{@namespace}.#{Naming.method_name(field["name"])}(#{passed})\nend\n"
      end

      def contributed_function_rbs(parent, field)
        params = [ref(parent["name"]), *ordered_args(field).map { param_rbs(it) }]
        "def self.#{Naming.method_name(field["name"])}: (#{params.join(", ")}) -> #{output_type(field)}"
      end

      private

      def object(type)
        includes = (type["interfaces"] || []).map { "  include #{ref(it["name"])}\n" }.join
        methods = Partition.own_fields(type).filter_map { method(type, it) }
        "class #{const(type)} < ::Dagger::Type\n#{includes}#{"\n" unless includes.empty?}  " \
          "def self.graphql_name = #{type["name"].dump}\n#{methods.map { "\n#{indent(it)}" }.join}end\n"
      end

      def interface(type)
        methods = Partition.own_fields(type).filter_map { method(type, it) }
        "module #{const(type)}\n#{methods.map { "#{indent(it)}\n" }.join}  " \
          "class Client < ::Dagger::Type\n    include #{const(type)}\n\n    " \
          "def self.graphql_name = #{type["name"].dump}\n  end\nend\n"
      end

      def enum(type)
        aliases, canonical = type.fetch("enumValues").partition { Schema.directive(it, "enumValue") }
        lines = canonical.map do |value|
          docs(value) + "#{Naming.constant(value["name"])} = new(#{value["name"].dump}, #{value["name"].dump})\n"
        end
        lines += aliases.map do |value|
          target = Schema.directive(value, "enumValue")&.fetch("value").to_s
          "#{Naming.constant(value["name"])} = #{Naming.constant(target)}\n"
        end
        "class #{const(type)} < ::Dagger::Enum\n#{indent(lines.join)}end\n"
      end

      def input(type)
        fields = type.fetch("inputFields")
        members = fields.map { ":#{Naming.argument_name(it["name"])}" }.join(", ")
        params = fields.map { "#{Naming.argument_name(it["name"])}:#{" nil" unless Schema.non_null?(it["type"])}" }
        names = fields.map { "#{Naming.argument_name(it["name"])}: #{it["name"].dump}" }.join(", ")
        "#{const(type)} = ::Data.define(#{members})\n\nclass #{const(type)}\n  include ::Dagger::Input\n\n  " \
          "def self.graphql_names = { #{names} }\n\n  " \
          "def initialize(#{params.join(", ")}) = super\nend\n"
      end

      def method(parent, field)
        name = field.fetch("name")
        return nil if name == "id"

        args = ordered_args(field)
        params = args.map { param(it) }
        selection = [name.dump, *args.map { select_arg(it) }].join(", ")
        signature = "def #{Naming.method_name(name)}#{"(#{params.join(", ")})" unless params.empty?}"
        "#{docs(field, args)}#{signature}\n#{indent(body(parent, field, "@query.select(#{selection})"))}end\n"
      end

      def ordered_args(field)
        required, optional = field.fetch("args").partition { !optional?(it) }
        required + optional
      end

      # Every entry point takes session:, so an argument of that name is renamed.
      def ruby_argument(arg, session: false)
        name = Naming.argument_name(arg.fetch("name"))
        session && name == "session" ? "session_" : name
      end

      def param(arg, session: false)
        name = ruby_argument(arg, session:)
        optional?(arg) ? "#{name}: nil" : "#{name}:"
      end

      def args_hash(args, session: false)
        return "{}" if args.empty?

        pairs = args.map do |arg|
          ruby = ruby_argument(arg, session:)
          arg["name"] == ruby ? "#{ruby}:" : "#{arg["name"]}: #{ruby}"
        end
        "{ #{pairs.join(", ")} }"
      end

      def optional?(arg) = !Schema.non_null?(arg["type"]) || !arg["defaultValue"].nil?

      def select_arg(arg)
        graphql = arg.fetch("name")
        ruby = Naming.argument_name(graphql)
        graphql == ruby ? "#{graphql}:" : "#{graphql}: #{ruby}"
      end

      def body(parent, field, selection)
        ref = field.fetch("type")
        named = Schema.named(ref)
        expected = Schema.expected_type(field)
        if named == "ID" && expected
          "#{selection}.execute_node(#{instance_const(expected)})\n"
        elsif list?(ref) && object_like?(named)
          "#{selection}.execute_object_list(#{instance_const(named)})\n"
        elsif object_like?(named) && !Schema.non_null?(ref)
          "#{reevaluated(field, selection)}.execute_optional(#{instance_const(named)})\n"
        elsif object_like?(named)
          "#{instance_const(named)}.new(#{reevaluated(field, selection)})\n"
        elsif named == "Void"
          "#{selection}.execute(allow_nil: true)\nnil\n"
        else
          leaf(ref, named, selection)
        end
      rescue Error => e
        raise Error, "#{parent["name"]}.#{field["name"]}: #{e.message}"
      end

      # An object built through a field marked @reevaluate fetches its ID on
      # each use; with when:, only once one of those arguments is true.
      def reevaluated(field, selection)
        directive = Schema.directive(field, "reevaluate") or return selection
        names = directive["when"] or return "#{selection}.reevaluate"
        "#{selection}.reevaluate_when(#{names.map { Naming.argument_name(it) }.join(", ")})"
      end

      def leaf(ref, named, selection)
        execute = Schema.non_null?(ref) ? "#{selection}.execute" : "#{selection}.execute(allow_nil: true)"
        convert = converter(named) or return "#{execute}\n"

        "#{convert_value(ref, execute, convert)}\n"
      end

      def converter(named)
        case @schema.kind(named)
        when "ENUM" then "#{ref(named)}.from_name"
        when "SCALAR" then generated?(named) ? "#{ref(named)}.new" : nil
        end
      end

      def convert_value(ref, value, convert)
        inner = Schema.non_null?(ref) ? ref["ofType"] : ref
        nullable = !Schema.non_null?(ref)
        if inner["kind"] == "LIST"
          element = convert_value(inner["ofType"], "it", convert)
          nullable ? "#{value}&.map { #{element} }" : "#{value}.map { #{element} }"
        elsif nullable
          "#{value}&.then { #{convert}(it) }"
        else
          "#{convert}(#{value})"
        end
      end

      def list?(ref) = (Schema.non_null?(ref) ? ref["ofType"] : ref).fetch("kind") == "LIST"

      def object_like?(name) = %w[OBJECT INTERFACE].include?(@schema.kind(name))

      def instance_const(name)
        @schema.kind(name) == "INTERFACE" ? "#{ref(name)}::Client" : ref(name)
      end

      def docs(node, args = [])
        lines = node["description"].to_s.strip.lines(chomp: true)
        args.each do |arg|
          text = arg["description"].to_s.strip
          lines << "@param #{Naming.argument_name(arg["name"])} #{text.lines(chomp: true).join(" ")}" unless text.empty?
        end
        lines << "@deprecated #{node["deprecationReason"]}".rstrip if node["isDeprecated"]
        experimental = Schema.directive(node, "experimental")
        lines << "@note Experimental: #{experimental["reason"]}".rstrip if experimental
        lines.map { "#{"# #{it}".rstrip}\n" }.join
      end

      def indent(text) = text.lines.map { |line| line.strip.empty? ? "\n" : "  #{line}" }.join

      def object_rbs(type)
        includes = (type["interfaces"] || []).map { "  include #{ref(it["name"])}\n" }.join
        methods = Partition.own_fields(type).filter_map { method_rbs(it) }
        "class #{const(type)} < ::Dagger::Type\n#{includes}  " \
          "def self.graphql_name: () -> ::String\n#{methods.map { "  #{it}\n" }.join}end\n"
      end

      def interface_rbs(type)
        methods = Partition.own_fields(type).filter_map { method_rbs(it) }
        "module #{const(type)} : ::Dagger::Type\n  @query: ::Dagger::QueryBuilder\n\n" \
          "#{methods.map { "  #{it}\n" }.join}\n  class Client < ::Dagger::Type\n    include #{const(type)}\n\n    " \
          "def self.graphql_name: () -> ::String\n  end\nend\n"
      end

      def enum_rbs(type)
        constants = type.fetch("enumValues").map { "  #{Naming.constant(it["name"])}: #{const(type)}\n" }.join
        "class #{const(type)} < ::Dagger::Enum\n#{constants}end\n"
      end

      def input_rbs(type)
        fields = type.fetch("inputFields")
        readers = fields.map { "  attr_reader #{Naming.argument_name(it["name"])}: #{input_type(it["type"], it)}\n" }
        params = fields.map do |field|
          optional = Schema.non_null?(field["type"]) ? "" : "?"
          "#{optional}#{Naming.argument_name(field["name"])}: #{input_type(field["type"], field)}"
        end.join(", ")
        "class #{const(type)} < ::Data\n  include ::Dagger::Input\n\n#{readers.join}\n  " \
          "def self.graphql_names: () -> ::Hash[::Symbol, ::String]\n  " \
          "def self.new: (#{params}) -> #{const(type)}\n  " \
          "def initialize: (#{params}) -> void\nend\n"
      end

      def method_rbs(field)
        name = field.fetch("name")
        return nil if name == "id"

        params = ordered_args(field).map { param_rbs(it) }
        "def #{Naming.method_name(name)}: (#{params.join(", ")}) -> #{output_type(field)}"
      end

      def param_rbs(arg, session: false)
        prefix = optional?(arg) ? "?" : ""
        type = input_type(arg["type"], arg)
        type = "#{type}?" if optional?(arg) && !type.end_with?("?")
        "#{prefix}#{ruby_argument(arg, session:)}: #{type}"
      end

      def output_type(field)
        ref = field.fetch("type")
        named = Schema.named(ref)
        expected = Schema.expected_type(field)
        return instance_rbs(expected) if named == "ID" && expected
        return "nil" if named == "Void"
        return wrap_output(ref, instance_rbs(named)) if object_like?(named) && list?(ref)
        return wrap_output(ref, instance_rbs(named)) if object_like?(named)

        wrap_output(ref, output_leaf_rbs(named))
      end

      def output_leaf_rbs(name)
        @schema.builtin_scalar?(name) ? leaf_rbs(name) : ref(name)
      end

      def wrap_output(ref, named, nullable: true)
        non_null = Schema.non_null?(ref)
        inner = non_null ? ref["ofType"] : ref
        type = inner["kind"] == "LIST" ? "::Array[#{wrap_output(inner["ofType"], named)}]" : named
        non_null || !nullable ? type : "#{type}?"
      end

      def input_type(ref, node)
        non_null = Schema.non_null?(ref)
        inner = non_null ? ref["ofType"] : ref
        type =
          if inner["kind"] == "LIST"
            "::Array[#{input_type(inner["ofType"], {})}]"
          else
            named_input(inner.fetch("name"), node)
          end
        non_null ? type : "#{type}?"
      end

      def named_input(name, node)
        return argument_object(Schema.expected_type(node)) if name == "ID"
        return leaf_rbs(name) if %w[SCALAR ENUM].include?(@schema.kind(name))

        ref(name)
      end

      def argument_object(expected)
        return "::Dagger::Type" unless expected

        @schema.kind(expected) == "INTERFACE" ? "::Dagger::Type & #{ref(expected)}" : ref(expected)
      end

      def instance_rbs(name)
        @schema.kind(name) == "INTERFACE" ? "#{ref(name)}::Client" : ref(name)
      end

      def leaf_rbs(name)
        case name
        when "String", "ID" then "::String"
        when "Int" then "::Integer"
        when "Float" then "::Float"
        when "Boolean" then "bool"
        else
          @schema.kind(name) == "SCALAR" ? "::String" : ref(name)
        end
      end
    end
  end
end
