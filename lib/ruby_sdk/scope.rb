require "json"
require "dagger"
require "dagger/mod"
require "dagger/clients/core"
require_relative "error"
require_relative "manifest"
require_relative "dang_config"
require_relative "codegen/naming"
require_relative "codegen/stand_in"
require_relative "signatures"
require_relative "resources"
require_relative "git_workspace"

class RubySdk
  # One directory the SDK manages, module or plain project. Its members are
  # written whole; what the SDK did not write is never written over or
  # deleted; the user's Gemfile gets at most one line.
  class Scope
    Core = ::Dagger::Clients::Core
    MARKER = ".dagger-generated".freeze
    EVAL_LINE = %(eval_gemfile "dagger.gemfile").freeze
    SKIPPED = %w[vendor/bundle .bundle].freeze
    SDK_FILES = %w[dagger-sdk.gemspec LICENSE .dagger-generated lib/**/*.rb sig/**/*.rbs exe/*].freeze
    GEMFILE = %(source "https://rubygems.org"\n\n#{EVAL_LINE}\n).freeze
    SIGNATURES = Dagger::Mod::Signatures::FILE
    DESCRIBE = %w[ruby -rbundler/setup sdk/exe/dagger-mod entrypoint --output /dagger/entrypoint].freeze

    Member = Data.define(:name, :dir, :ref, :pin, :source)

    SCOPE_BUNDLER = <<~'RUBY'.freeze
      require "bundler"

      lock, *expected = ARGV
      line = %(eval_gemfile "dagger.gemfile")
      read = lambda do
        Bundler::Definition.build("Gemfile", nil, nil).dependencies.filter_map do |dependency|
          next unless dependency.source.is_a?(Bundler::Source::Path)

          path = dependency.source.path.to_s
          "#{dependency.name} #{path}" if dependency.name.start_with?("dagger-sdk", "dagger-clients-") ||
                                          path == "sdk" || path.start_with?("clients/")
        end.sort
      end
      gems = read.call
      if gems.empty?
        gemfile = File.read("Gemfile")
        File.write("Gemfile", "#{gemfile}#{"\n" unless gemfile.end_with?("\n") || gemfile.empty?}\n#{line}\n")
        gems = read.call
      end
      missing = expected.sort - gems
      extra = gems - expected.sort
      unless missing.empty? && extra.empty?
        abort "the Gemfile does not resolve the SDK's gems as generated: " \
              "#{["missing #{missing.join(", ")}", "unexpected #{extra.join(", ")}"].reject { it.end_with?(" ") }.join("; ")}. " \
              "Keep #{line} in the Gemfile and remove other gems named dagger-sdk or dagger-clients-*"
      end
      exit unless lock == "true"
      exit 1 unless system("bundle", "lock", out: $stderr)

      # A Bundler other than the one the lock names restarts as that one, and
      # drops `ruby -rbundler/setup` doing so: the lock names the image's.
      locked = File.read("Gemfile.lock")
      File.write("Gemfile.lock", locked.sub(/^(BUNDLED WITH\n\s+)\S+/) { "#{$1}#{Bundler::VERSION}" })
    RUBY

    def initialize(ws:, is_module:, name:, clients:, sdk:, image:, target_version:, template: nil, ruby_version: "")
      @ws = ws
      @path = normalize(ws.cwd)
      @is_module = is_module
      @name = name
      @clients = clients
      @sdk = sdk
      @image = image
      @target_version = target_version
      @template = template
      @ruby_version = ruby_version
    end

    attr_reader :path

    def generated
      existing = @ws.directory(path: root)
      members = client_members
      self.class.check_members(@path, existing, members.map(&:dir))
      self.class.check_manifest(@path, existing) if @is_module
      self.class.check_dang_config(@path, existing, @target_version) if @is_module
      @resources = self.class.resources(@ws, @path)
      self.class.check_resources_engine(@path, @resources) if @is_module
      target = initialized(existing, @ws.with_workdir(path: "."))
      target = stale_clients(existing, members).reduce(target) do |ws, dir|
        ws.without_directory(path: at("clients/#{dir}"))
      end
      target = written(target, members)
      target = bundled(existing, with_gemfile(target), members)
      target = with_entrypoint(target, members) if @is_module
      target.with_workdir(path: @path)
    end

    def client_members
      members = @clients.map do |client|
        name = client.module_name
        next Member.new(name, Codegen::Naming.client_file(name), local_ref(client.source_root_subpath), nil, client) \
          if client.kind != Core::ModuleSourceKind::GIT_SOURCE || GitWorkspace.includes?(@ws, client)

        Member.new(name, Codegen::Naming.client_file(name), client.as_string, git_pin(client), client)
      end
      Codegen::Naming.client_files(members.map(&:name))
      members.sort_by(&:dir)
    rescue Codegen::Error => e
      raise Error, "#{@path}: #{e.message}"
    end

    def dagger_gemfile(members)
      gems = self.class.path_gems(members.map(&:dir))
      "# Code generated by dagger. DO NOT EDIT.\n#{gems.map { |gem, dir| %(gem "#{gem}", path: "#{dir}"\n) }.join}"
    end

    # The kind a member's marker names, compared as a whole string without
    # its final newline; anything else, or no marker, makes the directory the
    # user's.
    def self.kind(existing, dir)
      marker = "#{dir}/#{MARKER}"
      existing.exists(path: marker) ? existing.file(path: marker).contents.delete_suffix("\n") : ""
    end

    # A Gemfile marks a scope; a generated member carries a gemspec instead.
    def self.find_root(ws)
      found = ws.find_up(name: "Gemfile") or return nil
      directory = ::File.dirname(found.delete_prefix("/"))
      directory == "." || directory.empty? ? "." : directory
    end

    def self.local_ref(subpath)
      trimmed = subpath.delete_prefix("./").delete_prefix("/").delete_suffix("/")
      trimmed.empty? || trimmed == "." ? "/" : "/#{trimmed}"
    end

    # Generation's refusals, as class methods that read only what they are
    # given: the Steep check runs the same ones on a module (lib/ruby_sdk/steep.rb).
    def self.check_members(path, existing, client_dirs)
      expected = { "sdk" => "sdk", "clients/core" => "core", "clients/roots" => "roots" }
      client_dirs.each { expected["clients/#{it}"] = "client" }
      expected.each do |dir, kind|
        next unless existing.exists(path: dir)
        next if kind(existing, dir) == kind

        raise Error, "#{dir}/ exists in #{path} and was not written by dagger generate as its #{kind}; " \
                     "generation replaces it whole, so move or rename it, then run dagger generate again"
      end
    end

    def self.check_manifest(path, existing)
      if existing.exists(path: "dagger.json")
        raise Error, "#{path}/dagger.json is a manifest of an earlier Dagger; the Ruby SDK writes " \
                     "#{Manifest::FILE} only, so remove dagger.json, then run dagger generate again"
      end
      return unless existing.exists(path: Manifest::FILE)

      objections = Manifest.objections(existing.file(path: Manifest::FILE).contents)
      return if objections.empty?

      raise Error, "#{path}/#{Manifest::FILE} has what a Ruby module on its generated entrypoint cannot " \
                   "carry: #{objections.join("; ")}"
    end

    def self.check_dang_config(path, existing, target_version) = DangConfig.check(path, existing, target_version)

    # The gems dagger.gemfile names, and the directories that hold them.
    def self.path_gems(client_dirs)
      [%w[dagger-sdk sdk], %w[dagger-clients-core clients/core], %w[dagger-clients-roots clients/roots]] +
        client_dirs.map { ["dagger-clients-#{it}", "clients/#{it}"] }
    end

    def self.build_for(directory, image, name, client_dirs, resources: nil, path: ".")
      gemspecs = path_gems(client_dirs).map { |gem, dir| "#{dir}/#{gem}.gemspec" }
      Dagger::Mod::Build.new(image: module_image(directory, image), module_name: name, gemspecs:,
                             outside: resources ? resources.directories : [],
                             outside_files: resources ? resources.files : [], module_path: path)
    end

    # What the scope's build reads outside its directory, found in its
    # Gemfile, each path in the workspace and not all ignored by .gitignore,
    # which the engine applies to a local module's context.
    def self.resources(ws, path)
      root = ws.directory(path: "/")
      read = lambda do |relative|
        file = Resources.clean("#{path}/#{relative}")
        root.file(path: file).contents if root.exists(path: file)
      end
      resources = Resources.new(read, path == "." ? 0 : path.split("/").size)
      found = begin
        resources.found
      rescue Error => e
        raise Error, "#{path}: #{e.message}"
      end
      found.each do |one|
        file = Resources.clean("#{path}/#{one.path}")
        what = "#{path}: #{one.at}: #{one.path.dump}"
        raise Error, "#{what} names nothing in the workspace" unless root.exists(path: file)
        unless ws.directory(path: "/", include: [file], gitignore: true).exists(path: file)
          raise Error, "#{what} names only files that .gitignore ignores, which the engine does not load"
        end
      end
      resources
    end

    # A module with files outside its directory builds from CurrentModule's
    # contextDirectory and sourceSubpath: a feature, not a version. No schema
    # field tells whether the engine evaluates the entrypoint's sources.
    def self.check_resources_engine(path, resources)
      return if resources.patterns.empty?

      fields = Core.core.query.select("__type", name: "CurrentModule").select("fields").select("name")
                   .execute #: Array[Hash[String, String]]
      return if (%w[contextDirectory sourceSubpath] - fields.map { it["name"] }).empty?

      raise Error, "#{path}: the module's build reads #{resources.patterns.first.dump} outside its directory, which " \
                   "its entrypoint's sources returns for the engine to load with the module; this engine's " \
                   "CurrentModule has no contextDirectory and sourceSubpath, where the module would read it"
    end

    # The workspace's root with the scope and what sources returns only, at
    # their places: the context the engine loads with a module.
    def self.context(ws, path, scope, resources)
      excluded, included = resources.patterns.partition { it.start_with?("!") }
      include = included.map { Resources.clean("#{path}/#{it}") }
      exclude = excluded.map { Resources.clean("#{path}/#{it.delete_prefix("!")}") }
      ws.directory(path: "/", include:, exclude:, gitignore: true).with_directory(path:, source: scope)
    end

    # Bundler reads the Gemfile at generation as at build: the gems it
    # resolves from sdk/ and clients/ must be the members, exactly. With a
    # subpath, scope is its context and the scope sits there.
    def self.bundler(build, scope, lock, client_dirs, subpath: nil)
      expected = path_gems(client_dirs).map { |gem, dir| "#{gem} #{dir}" }
      base = Core.core.container.from(address: build.image)
      container = build.env(frozen: false).reduce(base) { |ctr, (name, value)| ctr.with_env_variable(name:, value:) }
      container.with_env_variable(name: "BUNDLE_GEMFILE", value: "#{bundler_dir(subpath)}/Gemfile")
               .with_new_file(path: "/scope-bundler.rb", contents: SCOPE_BUNDLER)
               .with_directory(path: "/scope", source: scope)
               .with_workdir(path: bundler_dir(subpath))
               .with_exec(args: ["ruby", "/scope-bundler.rb", lock.to_s, *expected], disable_dagger_in_dagger: true,
                          expect: Core::ReturnType::ANY)
    end

    def self.bundler_dir(subpath) = subpath ? "/scope/#{subpath}" : "/scope"

    def self.bundler_refusal(path, checked) = checked.exit_code.zero? ? nil : "#{path}: #{checked.stderr.strip}"

    # A path gem the lock resolves outside the module that the Gemfile names
    # in a way generation cannot read would be missing from the build.
    def self.lock_refusal(path, lock, resources)
      remote = lock.scan(/^PATH\n  remote: (.+)$/).flatten.find { !resources.covers?(it) } or return nil

      "#{path}: Gemfile.lock resolves the path gem at #{remote.dump}, which generation did not find in the Gemfile; " \
        "name it with a literal path: there, for the build to load it"
    end

    # dagger-mod entrypoint on the module's annotations as they are now, in
    # its installed container: the registry's every rule.
    def self.describe(installed, scope, subpath: nil)
      signatures = "#{subpath ? "/src/#{subpath}" : "/src"}/#{SIGNATURES}"
      installed.with_new_file(path: signatures, contents: Signatures.json(scope))
               .with_exec(args: DESCRIBE, disable_dagger_in_dagger: true, expect: Core::ReturnType::ANY)
    end

    def self.describe_refusal(path, described)
      return nil if described.exit_code.zero?

      "#{path}: describing the module failed: #{described.stderr.strip}"
    end

    # A module builds on ruby:<.ruby-version>, or on the SDK's pinned image.
    def self.module_image(directory, image)
      return image unless directory.exists(path: ".ruby-version")

      version = directory.file(path: ".ruby-version").contents.strip
      version.empty? ? image : "ruby:#{version}"
    end

    private

    def local_ref(subpath) = self.class.local_ref(subpath)

    # A git client loads the commit its ref resolved to when it was declared,
    # never whatever the ref names at load time.
    def git_pin(client)
      pin = client.pin
      return pin unless pin.empty?

      raise Error, "#{@path}: the git client #{client.as_string} has no pinned commit; declare it with " \
                   "`dagger module client add`, which pins it, then run dagger generate again"
    end

    def normalize(cwd)
      trimmed = cwd.delete_prefix("/").delete_suffix("/")
      trimmed.empty? ? "." : trimmed
    end

    def root = @path == "." ? "/" : "/#{@path}"

    def at(relative) = @path == "." ? "/#{relative}" : "/#{@path}/#{relative}"

    def stale_clients(existing, members)
      return [] unless existing.exists(path: "clients")

      declared = members.map(&:dir)
      existing.directory(path: "clients").entries.map { it.delete_suffix("/") }.select do |dir|
        dir != "core" && !declared.include?(dir) && self.class.kind(existing, "clients/#{dir}") == "client"
      end
    end

    # A module scope with no manifest yet gets the template's files, each
    # only where the scope has none.
    def initialized(existing, target)
      unless @ruby_version.empty?
        target = target.with_new_file(path: at(".ruby-version"),
                                      contents: "#{@ruby_version}\n")
      end
      return target unless @template && @is_module && !existing.exists(path: Manifest::FILE)

      template_files.reduce(target) do |ws, (relative, contents)|
        existing.exists(path: relative) ? ws : ws.with_new_file(path: at(relative), contents:)
      end
    end

    def template_files
      class_name = Dagger::Mod::Naming.to_camel(@name)
      file = Dagger::Mod::Naming.file_name(@name)
      directory = @sdk.directory(path: "templates/#{@template}")
      walk(directory).to_h do |relative|
        contents = directory.file(path: relative).contents
        rendered = relative.delete_suffix(".tmpl").gsub("{{file}}", file)
        [rendered, contents.gsub("{{name}}", @name).gsub("{{class}}", class_name).gsub("{{file}}", file)]
      end
    end

    def walk(directory, prefix = "")
      directory.entries.flat_map do |entry|
        next [prefix + entry] unless entry.end_with?("/")

        walk(directory.directory(path: entry), prefix + entry)
      end
    end

    def written(target, members)
      target = target.with_new_directory(path: at("sdk"),
                                         source: @sdk.directory(path: "sdk").filter(include: SDK_FILES))
      core = core_member
      target = target.with_new_directory(path: at("clients/core"), source: core)
      digest = core.file(path: "lib/dagger/clients/core.rb").contents[/CORE_DIGEST = "([^"]+)"/, 1] or
        raise Error, "the generated core carries no CORE_DIGEST"
      members.each do |member|
        target = target.with_new_directory(path: at("clients/#{member.dir}"), source: client_member(member, digest))
      end
      target.with_new_directory(path: at("clients/roots"), source: roots_member(members))
            .with_new_file(path: at("dagger.gemfile"), contents: dagger_gemfile(members))
    end

    def stand_in
      Codegen::StandIn::FILES.reduce(Core.core.directory) { |dir, (path, contents)| dir.with_new_file(path:, contents:) }
                             .as_module_source
                             .with_engine_version(version: @target_version)
    end

    # Every schema in one view, the target's: two views would give two cores.
    def core_member = codegen(stand_in.client_schema_introspection_json, %w[core /schemas/schema.json /out])

    def client_member(member, digest)
      codegen(client_schema(member),
              ["client", "/schemas/schema.json", "/out", member.name, member.ref, digest, member.pin].compact)
    end

    # Every client's schema in one exec, for the one module of their methods.
    def roots_member(members)
      schemas = members.each_with_index.to_h { |member, index| ["/schemas/#{index}.json", client_schema(member)] }
      codegen_with(schemas, ["roots", "/out", *schemas.keys.zip(members.map(&:name)).flatten])
    end

    def client_schema(member)
      member.source.with_engine_version(version: @target_version).client_schema_introspection_json
    end

    def codegen(schema, args) = codegen_with({ "/schemas/schema.json" => schema }, args)

    def codegen_with(schemas, args)
      container = Core.core.container.from(address: @image)
                      .with_mounted_directory(path: "/codegen", source: @sdk.directory(path: "lib"))
      schemas.reduce(container) { |ctr, (path, schema)| ctr.with_mounted_file(path:, source: schema) }
             .with_exec(args: ["ruby", "/codegen/ruby_sdk/codegen/cli.rb", *args], disable_dagger_in_dagger: true)
             .directory(path: "/out")
    end

    # Bundler reads the Gemfile at generation as at build: the gems it
    # resolves from sdk/ and clients/ must be the members, exactly. A module
    # always has a lock, written by the Bundler of the image that builds it.
    def bundled(existing, target, members)
      lock = @is_module || existing.exists(path: "Gemfile.lock")
      build = build(target, members)
      source, subpath = layout(target, build)
      checked = self.class.bundler(build, source, lock, members.map(&:dir), subpath:)
      refused = self.class.bundler_refusal(@path, checked)
      raise Error, refused if refused

      dir = self.class.bundler_dir(subpath)
      target = target.with_file(path: at("Gemfile"), source: checked.file(path: "#{dir}/Gemfile"))
      return target unless lock

      locked = checked.file(path: "#{dir}/Gemfile.lock")
      refused = self.class.lock_refusal(@path, locked.contents, @resources)
      raise Error, refused if refused

      target.with_file(path: at("Gemfile.lock"), source: locked)
    end

    # What Bundler and the module's container see: the scope alone, or the
    # context it sits in at a subpath, beside what it uses outside it.
    def layout(target, build)
      scope = target.directory(path: root, exclude: SKIPPED)
      return [scope, nil] unless build.context?

      [self.class.context(target, @path, scope, @resources), @path]
    end

    # A scope without a Gemfile gets one; a new module has its template's.
    def with_gemfile(target)
      return target if target.directory(path: root).exists(path: "Gemfile")

      target.with_new_file(path: at("Gemfile"), contents: GEMFILE)
    end

    def build(target, members)
      self.class.build_for(target.directory(path: root), @image, @name, members.map(&:dir),
                           resources: @resources, path: @path)
    end

    # The module's types are in its annotations, which only generation
    # reads: dagger-mod describes the module with what it read, and writes
    # the module's own RBS beside the entrypoint.
    def with_entrypoint(target, members)
      scope = target.directory(path: root, exclude: SKIPPED)
      build = build(target, members)
      source, subpath = layout(target, build)
      installed = Core::Container.new(build.installed(Core.core.query, source, subpath:))
      described = self.class.describe(installed, scope, subpath:)
      refused = self.class.describe_refusal(@path, described)
      raise Error, refused if refused

      target.with_new_directory(path: at("sdk/entrypoint"), source: rendered(described, build, subpath))
            .with_new_file(path: at(Manifest::FILE), contents: Manifest.render(@name))
    end

    # What dagger-mod wrote, with the build and, for a module that reads
    # files outside its directory, the main.dang that returns them.
    def rendered(described, build, subpath)
      signatures = described.file(path: "#{subpath ? "/src/#{subpath}" : "/src"}/#{SIGNATURES}")
      rendered = described.directory(path: "/dagger/entrypoint")
                          .with_new_file(path: "build.dang", contents: build.to_dang)
                          .with_file(path: ::File.basename(SIGNATURES), source: signatures)
      return rendered unless build.context?

      main = Dagger::Mod::Entrypoint.render_main(@name, outside: build.outside, outside_files: build.outside_files)
      rendered.with_new_file(path: "main.dang", contents: main)
    end
  end
end
